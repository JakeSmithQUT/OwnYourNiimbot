// Writes docs/supported-printers.md from src/printer/models.ts.
import { build } from 'esbuild';
import { writeFileSync } from 'node:fs';

const result = await build({
  entryPoints: ['src/printer/models.ts'],
  bundle: true,
  format: 'esm',
  platform: 'node',
  write: false,
});
const code = result.outputFiles[0].text;
const mod = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const { MODELS, PRINT_VARIANTS, defaultVariant } = mod;

const LABEL_TYPES = { 1: 'gap', 2: 'black mark', 3: 'continuous', 4: 'perforated', 5: 'transparent', 6: 'PVC tag', 10: 'black mark gap', 11: 'heat-shrink tube' };
const variantName = (m) => PRINT_VARIANTS.find((v) => v.value === defaultVariant(m))?.label ?? '';

const supported = MODELS.filter((m) => m.protocol === 'niimbot');
const other = MODELS.filter((m) => m.protocol !== 'niimbot');

const rows = supported.map((m) =>
  `| ${m.name} | ${m.ids.join(', ') || '–'} | ${m.dpi} | ${m.printWidthMm.max ?? '–'} mm | ${m.density.min}–${m.density.max} (${m.density.default}) | ${m.paperTypes.map((t) => LABEL_TYPES[t] ?? t).join(', ')} | ${variantName(m)} |`,
);

const md = `# Supported printers

This file is generated by \`node scripts/printer-table.mjs\`. Do not edit it by hand.

The model data comes from the printer list in the official app. The app uses the model ID that the printer reports to find the model.

## NIIMBOT command set

These ${supported.length} models use the NIIMBOT command set. The last column shows the command set that the app selects automatically. To use a different command set, change **Settings > Command set** or open **Advanced** in the print dialog.

| Model | Model IDs | DPI | Print width | Density (default) | Label types | Command set |
|---|---|---|---|---|---|---|
${rows.join('\n')}

## Models with a different command set

The official app lists these models, but they use a command set from a different manufacturer. This app does not support them.

| Model | Model IDs | Command set |
|---|---|---|
${other.map((m) => `| ${m.name} | ${m.ids.join(', ') || '–'} | ${m.protocol} |`).join('\n')}

## Hardware test status

The print commands are tested against a simulated printer in \`tests/client.test.ts\`. If you print with a model, open an issue with the model name, the firmware version and the result. Attach the communication log from the **Printer** page if the print fails.
`;

writeFileSync('docs/supported-printers.md', md);
console.log(`Wrote docs/supported-printers.md (${supported.length} supported, ${other.length} other)`);
