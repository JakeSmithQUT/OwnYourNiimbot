export const COMMON_ICONS: SymbolEntry[] = COMMON_NAMES.map((n) => ICONS.find((i) => i.name === n)).filter((i): i is SymbolEntry => Boolean(i));

/** Symbols with a name or a group that contains every word of the search text. */
export function searchIcons(query: string): SymbolEntry[] {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return ICONS;
  return ICONS.filter((i) => words.every((w) => i.name.includes(w) || i.group.toLowerCase().includes(w)));
}

export function iconSvg(Icon: LucideIcon): string {
  // Solid parts of a symbol take the text colour on the screen. A label has no text colour, so they are black there.
  return renderToStaticMarkup(<Icon size={96} color="#000000" strokeWidth={2} />).replace(/currentColor/g, '#000000');
}
